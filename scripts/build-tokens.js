#!/usr/bin/env node
'use strict';
// Design Spec v3, section 1b and Part B9 step 7 (Obsidian BYP-DESIGN-SPEC.md, signed off by Lewis 16 Nov 2026): one
// system for every brand, only the colour changes. The token layers live in tokens/ (not served, see .assetsignore):
//   system.css   type, space, radii, sizes, motion, brand shades worked out from --brand (copied unchanged from Before You Pay)
//   modes.css    light: colours, surfaces, lines, status tones, depth, the app frame (copied unchanged from Before You Pay)
//   brand.css    Phillips.: --brand and its pins (the only file that differs between brands), always last
//   v5-core.css  the group's v5 stylesheet (copied unchanged from the phillips-group repo); only v5.css gets it, after the tokens
// Light only: modes-dark.css and modes-glass.css are not copied here (the global rule "Light only. No dark mode").
// Pages still load one stylesheet: this script copies the token files between each target's "tokens:start" and
// "tokens:end" markers. Edit the token files, never the copied block, then run:
//   node scripts/build-tokens.js           write the block into every target
//   node scripts/build-tokens.js --check   exit 1 if any target is out of date (scripts/test-tokens.cjs runs this)
// After a change, bump the target's ?v= on every page that loads it (agency.css, guides.css).

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const LIGHT = ['system', 'modes', 'brand'].map(n => `tokens/${n}.css`);
const TARGETS = [
  { file: 'agency.css', sources: LIGHT },                      // the website: home, services, work, about, privacy, Brief, free tools
  { file: 'guides.css', sources: LIGHT },                      // Insights hub and the guides (each keeps its own <style> too)
  { file: 'cloudflare/private/admin.html', sources: LIGHT },   // the admin (light only)
  { file: 'cloudflare/private/rate-card.html', sources: LIGHT }, // the rate card invite page
  { file: 'v5.css', sources: [...LIGHT, 'tokens/v5-core.css'] },   // the pages on v5 (26 Nov 2026): tokens, then the group's v5 core
];
const START = '/* tokens:start (generated by scripts/build-tokens.js from tokens/*.css; edit those files, not this block) */';
const END = '/* tokens:end */';

function block(sources) {
  const parts = sources.map(f => `/* ── ${f} ── */\n` + fs.readFileSync(path.join(ROOT, f), 'utf8').trim());
  return `${START}\n${parts.join('\n\n')}\n${END}`;
}

function build(src, sources) {
  const b = block(sources);
  const i = src.indexOf(START.slice(0, 20)), j = src.indexOf(END);
  if (i === -1 || j === -1 || j < i) throw new Error('The tokens:start and tokens:end markers are missing or out of order');
  return src.slice(0, i) + b + src.slice(j + END.length);
}

module.exports = { block, build, TARGETS, START, END };

if (require.main === module) {
  const check = process.argv.includes('--check');
  let stale = 0;
  for (const t of TARGETS) {
    const file = path.join(ROOT, t.file), src = fs.readFileSync(file, 'utf8'), out = build(src, t.sources);
    if (out === src) { console.log(`${t.file}: up to date`); continue; }
    if (check) { console.log(`${t.file}: OUT OF DATE, run node scripts/build-tokens.js`); stale++; continue; }
    fs.writeFileSync(file, out);
    console.log(`${t.file}: tokens written`);
  }
  if (stale) process.exit(1);
}
